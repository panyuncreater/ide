// ============================================================
// TokenPuzzleData.cpp — 交互式 Token 拼图游戏关卡数据实现（功能 3）
// ------------------------------------------------------------
// 5 个关卡数据嵌入本文件，与 BugHuntLibrary.cpp 模式一致。
// 独立编译单元，仅依赖标准库（std::string / std::vector），
// 不依赖 Qt Widgets / IdeController.h / 引擎层——可安全加入
// minilang_tests 测试目标。
//
// shuffledTokens 为 tokens 的固定乱序（硬编码，非运行时随机），
// 保证可重现并满足"确实打乱"的测试断言。乱序顺序已人工校验：
//   - 与 tokens 构成相同多重集（元素相同仅顺序不同）
//   - 与 tokens 顺序不完全相同（确实打乱）
// ============================================================

#include "gui/TokenPuzzleData.h"

const std::vector<TokenPuzzleLevel>& TokenPuzzleLibrary::levels() {
    static const std::vector<TokenPuzzleLevel> kLevels = {
        // ----------------------------------------------------------
        // 关卡 1：var x = 42;  — 基本 5 个 token（⭐）
        // ----------------------------------------------------------
        TokenPuzzleLevel{
            1,
            "var x = 42;",
            {"var", "x", "=", "42", ";"},
            {"=", "42", "var", ";", "x"},
            "基本 5 个 token：关键字 var、标识符 x、等号 =、数字字面量 42、分号 ;",
            "以关键字 var 开头，以分号 ; 结尾",
            1
        },
        // ----------------------------------------------------------
        // 关卡 2：print("hello");  — 字符串是一个 token（⭐）
        // ----------------------------------------------------------
        TokenPuzzleLevel{
            2,
            "print(\"hello\");",
            {"print", "(", "\"hello\"", ")", ";"},
            {"\"hello\"", ")", "print", ";", "("},
            "字符串是一个 token（不是 7 个）—— 引号内的内容整体作为一个 STRING token",
            "print 是函数名，括号内的 \"hello\" 是一个完整的字符串 token",
            1
        },
        // ----------------------------------------------------------
        // 关卡 3：x > 0 and y < 10;  — 运算符优先级不影响切分（⭐⭐）
        // ----------------------------------------------------------
        TokenPuzzleLevel{
            3,
            "x > 0 and y < 10;",
            {"x", ">", "0", "and", "y", "<", "10", ";"},
            {"and", "10", ">", "y", ";", "0", "x", "<"},
            "运算符优先级不影响 token 切分—— and 是关键字运算符，> 和 < 是独立 token",
            "and 是逻辑运算符关键字，> 和 < 各自是一个 token，从左到右切分",
            2
        },
        // ----------------------------------------------------------
        // 关卡 4：// 这是注释\nprint(1);  — 注释被分离出主流（⭐⭐）
        // ----------------------------------------------------------
        TokenPuzzleLevel{
            4,
            "// 这是注释\nprint(1);",
            {"// 这是注释", "print", "(", "1", ")", ";"},
            {"(", "1", "// 这是注释", ")", ";", "print"},
            "注释被分离出主流——整行注释作为一个独立单元，不参与语法分析",
            "注释以 // 开头到行尾，是一个独立单元；print(1); 是真正的代码",
            2
        },
        // ----------------------------------------------------------
        // 关卡 5：a[0] = b["key"] + 1;  — 复杂表达式（⭐⭐⭐）
        // ----------------------------------------------------------
        TokenPuzzleLevel{
            5,
            "a[0] = b[\"key\"] + 1;",
            {"a", "[", "0", "]", "=", "b", "[", "\"key\"", "]", "+", "1", ";"},
            {"=", "\"key\"", "[", "1", "a", "]", "+", "b", "0", "[", ";", "]"},
            "复杂表达式——数组索引、赋值、字符串键、加法运算的 token 组合",
            "从左到右逐字符切分：a [ 0 ] = b [ \"key\" ] + 1 ;",
            3
        }
    };
    return kLevels;
}
