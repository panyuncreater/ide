// ============================================================
// TokenPuzzleData.cpp — 交互式 Token 拼图游戏关卡数据实现（功能 3）
// ------------------------------------------------------------
// 5 个关卡数据嵌入本文件，与 BugHuntLibrary.cpp 模式一致。
// 独立编译单元，仅依赖标准库（std::string / std::vector），
// 不依赖 Qt Widgets / IdeController.h / 引擎层——可安全加入
// minilang_tests 测试目标。
//
// shuffledTokens 为 tokens 的固定乱序（硬编码，非运行时随机），
// 保证可重现并满足"确实打乱"的测试断言。乱序顺序已人工校验：
//   - 与 tokens 构成相同多重集（元素相同仅顺序不同）
//   - 与 tokens 顺序不完全相同（确实打乱）
//
// 教学理念：词法分析（Lexer）的本质是"把连续的字符流切成最小
// 的有意义单元（token）"。本库通过游戏化拼图，让学习者用身体
// 记住"切分边界"在哪里——这是理解编译全过程的第一块基石。
// ============================================================

#include "gui/TokenPuzzleData.h"

const std::vector<TokenPuzzleLevel>& TokenPuzzleLibrary::levels() {
    static const std::vector<TokenPuzzleLevel> kLevels = {
        // ----------------------------------------------------------
        // 关卡 1：var x = 42;  — 基本 5 个 token（⭐）
        // ----------------------------------------------------------
        TokenPuzzleLevel{
            1,
            "var x = 42;",
            {"var", "x", "=", "42", ";"},
            {"=", "42", "var", ";", "x"},
            "🔤 什么是 token？\n"
            "• 类比：词法分析就像把连续的中文句子「断词」——「今天天气好」会被切成 今天／天气／好。代码也一样，编译器先把字符流切成一个个「最小有意义单元」，这每个单元就叫一个 token。\n"
            "• 本关 5 个 token 各司其职：\n"
            "    var  → 关键字（keyword），告诉编译器「我要声明变量了」\n"
            "    x    → 标识符（identifier），变量的名字\n"
            "    =    → 赋值运算符\n"
            "    42   → 数字字面量（number literal）\n"
            "    ;    → 语句结束符，像句号一样划清一句代码的边界",
            "💡 复原顺序：以关键字 var 开头，接着是变量名 x，然后是 =、数字 42，最后用分号 ; 收尾。\n"
            "   记忆口诀：关键字 → 名字 → 等号 → 值 → 分号。",
            1
        },
        // ----------------------------------------------------------
        // 关卡 2：print("hello");  — 字符串是一个 token（⭐）
        // ----------------------------------------------------------
        TokenPuzzleLevel{
            2,
            "print(\"hello\");",
            {"print", "(", "\"hello\"", ")", ";"},
            {"\"hello\"", ")", "print", ";", "("},
            "🔤 字符串是一个整体 token！\n"
            "• 类比：字符串就像一封封装好的信封——从外面看它是一个完整的包裹，信封里写的是「hello」还是「world」不影响它「一个包裹」的身份。\n"
            "• 源码里的 「hello」（连同两侧引号）被词法分析器当成一个 STRING token，而不是 7 个零散字符 h-e-l-l-o。\n"
            "• 本关 token：print（函数名/标识符）· ( · 「hello」（一整个字符串 token）· ) · ;",
            "💡 还原时把 「hello」 当作一个不可分割的方块：顺序是 print → ( → 「hello」 → ) → ;。\n"
            "   千万别把 hello 拆开！引号内的所有东西在词法阶段都属于同一个 token。",
            1
        },
        // ----------------------------------------------------------
        // 关卡 3：x > 0 and y < 10;  — 运算符优先级不影响切分（⭐⭐）
        // ----------------------------------------------------------
        TokenPuzzleLevel{
            3,
            "x > 0 and y < 10;",
            {"x", ">", "0", "and", "y", "<", "10", ";"},
            {"and", "10", ">", "y", ";", "0", "x", "<"},
            "🔤 切词只关心「边界」，不关心「先算谁」。\n"
            "• 类比：断词时我们只决定「和」是不是一个词，不会因为后面跟着「去」就改变它自身的切分。运算符优先级（先乘除后加减、and 的绑定强弱）是「语法/语义阶段」才管的，词法阶段一律从左到右、见边界就切。\n"
            "• 本关要点：and 是逻辑运算符关键字（一个 token）；> 和 < 各自是独立 token；它们谁先算，词法分析器一概不管。",
            "💡 从左到右顺序复原：x → > → 0 → and → y → < → 10 → ;。\n"
            "   提示：and 是一个完整的关键字 token，不要和前后运算符拆开；> 与 < 各占一格。",
            2
        },
        // ----------------------------------------------------------
        // 关卡 4：// 这是注释\nprint(1);  — 注释被分离出主流（⭐⭐）
        // ----------------------------------------------------------
        TokenPuzzleLevel{
            4,
            "// 这是注释\nprint(1);",
            {"// 这是注释", "print", "(", "1", ")", ";"},
            {"(", "1", "// 这是注释", ")", ";", "print"},
            "🔤 注释被「剔除」出主流。\n"
            "• 类比：注释就像书页边上的眉批——是写给读代码的人看的，编译器看完就当没看见。词法分析器一旦遇到 // ，会一直「吃到行尾」，把整行注释吞成一个独立单元后直接丢弃，不参与后续任何分析。\n"
            "• 所以真正进入「语法分析」的只有 print(1); 这 5 个 token，注释从始至终不影响程序含义。",
            "💡 先放整行注释 // 这是注释（它是一个独立单元），再依次排 print → ( → 1 → ) → ;。\n"
            "   记住：注释整行打包，真正的代码才是后面的 print(1);。",
            2
        },
        // ----------------------------------------------------------
        // 关卡 5：a[0] = b["key"] + 1;  — 复杂表达式（⭐⭐⭐）
        // ----------------------------------------------------------
        TokenPuzzleLevel{
            5,
            "a[0] = b[\"key\"] + 1;",
            {"a", "[", "0", "]", "=", "b", "[", "\"key\"", "]", "+", "1", ";"},
            {"=", "\"key\"", "[", "1", "a", "]", "+", "b", "0", "[", ";", "]"},
            "🔤 再长再复杂的表达式，也遵循同一套切分规则。\n"
            "• 类比：长句子照样按固定规则逐字断词。遇到 [ 和 ] 就各切一个 token；遇到 「key」 又是一个整体字符串 token；+ 和 = 各是运算符 token。\n"
            "• 完整 token 序列（共 12 个）：\n"
            "    a · [ · 0 · ] · = · b · [ · 「key」 · ] · + · 1 · ;\n"
            "• 观察：0 和 「key」 都待在方括号里，但各自仍是独立 token，方括号只是「容器边界」而已。",
            "💡 从左到右逐字符切：a、[、数字 0、]、=、b、[、「key」(整体)、]、+、数字 1、;。\n"
            "   易错点：把 [ ] 当成一对整体——其实它们是左右两个独立 token；「key」 不要拆。",
            3
        }
    };
    return kLevels;
}
