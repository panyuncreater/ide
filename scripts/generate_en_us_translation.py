MSG_OPEN = "    <message>"
MSG_CLOSE = "    </message>"


def parse_messages(content):
    """Return list of (source_text, leading_source_line_prefix, source_inline).

    Each message block is parsed to extract the raw <source>...</source>
    inner text (preserving newlines and XML escaping). We also remember
    whether the source was inline (single line) or block (multi-line) so we
    can reproduce the same shape.
    """
    messages = []
    lines = content.split("\n")
    i = 0
    n = len(lines)
    while i < n:
        line = lines[i]
        if line.strip() == MSG_OPEN.strip():
            # find source
            j = i + 1
            # expect <source>...</source> possibly on following lines
            # gather until </message>
            block = []
            while j < n and lines[j].strip() != MSG_CLOSE.strip():
                block.append(lines[j])
                j += 1
            src, src_shape = extract_source(block)
            messages.append((src, src_shape))
            i = j + 1
        else:
            i += 1
    return messages


def extract_source(block_lines):
    """Given the lines inside <message>...</message>, return (source, shape).

    shape is 'inline' if <source>x</source> is on one line, else 'block'
    where the source content starts on the line after <source> (which may be
    empty) and ends before </source>.
    """
    # Join to locate <source> and </source>
    # Find the line containing <source>
    src_open_idx = None
    for idx, ln in enumerate(block_lines):
        if "<source>" in ln:
            src_open_idx = idx
            break
    if src_open_idx is None:
        return "", "inline"

    open_line = block_lines[src_open_idx]
    after_open = open_line.split("<source>", 1)[1]

    if "</source>" in after_open:
        # inline single-line source
        src = after_open.split("</source>", 1)[0]
        return src, "inline"

    # Multi-line: content may start right after <source> on same line or
    # on following lines until the line with </source>.
    parts = []
    first = after_open  # could be "" or have content
    parts.append(first)
    idx = src_open_idx + 1
    while idx < len(block_lines):
        ln = block_lines[idx]
        if "</source>" in ln:
            before_close = ln.split("</source>", 1)[0]
            parts.append(before_close)
            break
        else:
            parts.append(ln)
        idx += 1
    # The original zh_CN format puts <source> alone on its line, then the
    # content lines follow. Reconstruct exactly: content = "\n".join(parts)
    # but parts[0] is the empty string after <source>. To reproduce the
    # file's exact shape we join with "\n".
    # However if parts[0] is "" and parts has >1 entries, the real content
    # is "\n".join(parts[1:]) with a leading newline implied. We keep the
    # full join to preserve leading newline semantics:
    src = "\n".join(parts)
    # If the source began with a newline (parts[0]=="") strip the artificial
    # leading empty entry only if there was truly nothing after <source>.
    # We keep src as-is; serialization reconstructs faithfully.
    return src, "block"


def render_messages(messages):
    """Render messages back into the body of the <context> element."""
    out = []
    for src, shape in messages:
        out.append(MSG_OPEN)
        translation = translate(src)
        if shape == "inline":
            out.append("        <source>{}</source>".format(src))
            out.append('        <translation type="finished">{}</translation>'.format(translation))
        else:
            # block form: <source>\n<content>\n</source>
            # src already includes the leading empty (newline) and content.
            # Reconstruct: the original had "<source>" on its own line, then
            # content lines, then "</source>".
            # src is "\n".join(parts) where parts[0] is whatever followed
            # <source> (usually "").
            content_lines = src.split("\n")
            # parts[0] is after-open (usually ""); drop it if empty because
            # it represents nothing after <source> on the same line.
            if content_lines and content_lines[0] == "":
                body_lines = content_lines[1:]
            else:
                body_lines = content_lines
            out.append("        <source>")
            out.extend(body_lines)
            out.append("        </source>")
            # translation block mirrors source shape
            tlines = translation.split("\n")
            if tlines and tlines[0] == "" and len(tlines) > 1:
                tbody = tlines[1:]
            else:
                tbody = tlines
            out.append('        <translation type="finished">')
            out.extend(tbody)
            out.append("        </translation>")
        out.append(MSG_CLOSE)
    return "\n".join(out)


def main():
    if not os.path.isfile(SRC):
        print("ERROR: source not found:", SRC, file=sys.stderr)
        return 1

    with open(SRC, "r", encoding="utf-8") as f:
        content = f.read()

    messages = parse_messages(content)

    total = len(messages)
    translated = 0
    kept = 0
    for src, _ in messages:
        if has_cjk(src):
            translated += 1
        else:
            kept += 1

    header = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!DOCTYPE TS>\n"
        '<TS version="2.1" language="en_US">\n'
        "<!--\n"
        "  MiniLang IDE translation file (English, US).\n"
        "  Generated from zh_CN.ts by scripts/generate_en_us_translation.py.\n"
        "-->\n"
        "<context>\n"
        "    <name>MiniLang</name>\n"
    )
    body = render_messages(messages)
    footer = "</context>\n</TS>\n"

    output = header + body + "\n" + footer

    # Validate XML.
    try:
        minidom.parseString(output)
        valid = True
    except Exception as e:
        valid = False
        print("XML VALIDATION ERROR:", e, file=sys.stderr)

    with open(DST, "w", encoding="utf-8", newline="\n") as f:
        f.write(output)

    print("Total messages processed:", total)
    print("Messages with Chinese translated:", translated)
    print("Messages kept as-is (pure code):", kept)
    print("Output written to:", DST)
    print("Valid XML:", valid)
    if total != 1296:
        print("WARNING: expected 1296 messages, got", total, file=sys.stderr)
    return 0 if valid else 2


if __name__ == "__main__":
    sys.exit(main())
