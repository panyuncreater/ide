# Pre-build a list of (cn, en) sorted by length of cn descending, so longer
# phrases are replaced before their sub-strings. Deduplicate by cn, keeping
# the first (most specific) mapping.
def _build_sorted_phrases():
    seen = set()
    ordered = []
    for cn, en in PHRASES:
        if cn in seen:
            continue
        seen.add(cn)
        ordered.append((cn, en))
    ordered.sort(key=lambda kv: len(kv[0]), reverse=True)
    return ordered

SORTED_PHRASES = _build_sorted_phrases()

CJK_RE = re.compile(r"[\u4e00-\u9fff]")


def has_cjk(s):
    return bool(CJK_RE.search(s))


def translate(text):
    """Translate a single source string into English."""
    if not has_cjk(text):
        return text  # Rule 6: pure code, keep as-is

    out = text
    # P2-13 fix: Use position-aware replacement to insert spaces at translation
    # boundaries. Original str.replace(cn, en) merges adjacent translations:
    # e.g. "栈式操作码" → "栈式"="stack-based" + "操作码"="opcode" → "stack-basedopcode".
    # Fix: after replacing a CJK phrase, if the next char is CJK or Latin letter,
    # insert a space; if the previous char is a Latin letter, also insert a space.
    # This ensures adjacent translated phrases are separated by spaces.
    # P2-13 fix2: Skip non-CJK phrases (e.g. ("op","op")) to prevent matching
    # within English words produced by earlier translations (e.g. "Scope" → "Sc op e").
    for cn, en in SORTED_PHRASES:
        if not has_cjk(cn):
            continue  # Skip pure-Latin entries; they match within translated English
        if cn not in out:
            continue
        pattern = re.escape(cn)
        cn_re = re.compile(pattern)

        def _repl(m, _en=en, _cur=out):
            start = m.start()
            end = m.end()
            prefix = ""
            suffix = ""
            # P2-13 fix2: Only insert prefix space if prev char is an ASCII letter
            # (CJK chars are handled by their own replacement; isalpha() is True for CJK)
            if start > 0:
                prev_ch = _cur[start - 1]
                if prev_ch.isascii() and prev_ch.isalpha():
                    prefix = " "
            if end < len(_cur):
                next_ch = _cur[end]
                # Insert suffix space if next is CJK (will be translated) or ASCII letter
                if CJK_RE.match(next_ch) or (next_ch.isascii() and next_ch.isalpha()):
                    suffix = " "
            return prefix + _en + suffix

        out = cn_re.sub(_repl, out)

    # Normalize full-width punctuation to half-width.
    for fw, hw in PUNCT.items():
        if fw in out:
            out = out.replace(fw, hw)

    # Tidy up double spaces introduced by mapping function words to " ".
    while "  " in out:
        out = out.replace("  ", " ")
    # Strip spaces before punctuation that English doesn't use.
    out = re.sub(r"\s+([,.;:!?])", r"\1", out)
    # P2-13 fix: Strip space before closing parenthesis/bracket.
    out = re.sub(r"\s+([)\]])", r"\1", out)
    # P2-13 fix: Strip space after opening parenthesis/bracket.
    out = re.sub(r"([(])\s+", r"\1", out)
    # Strip a leading space that may have been introduced.
    if out.startswith(" ") and not text.startswith(" "):
        out = out[1:]

    return out


